using System;
using System.Linq;
using System.Text;
using System.Collections.Generic;

namespace ModernWestern.UEArchitecture.EditorTools
{
    /// <summary>
    /// The C# file of tag constants ("Generate C# constants"): <c>Tags.Status.Burning</c> instead of
    /// <c>GameplayTag.Request("Status.Burning")</c>, so a typo is a compile error. Pure (tested): a tag with children is a
    /// nested static class whose own tag is its <c>Tag</c> field (<c>Tags.Status.Tag</c>); names that C# would not accept
    /// are escaped (keywords get '@', a leading digit gets '_', a clash with the enclosing class gets a trailing '_'). A
    /// name that needs no escaping always belongs to its own tag; when an escaped name is a sibling's own name ("1Up" and
    /// "_1Up"), the clash is reported so the file is not written.
    /// </summary>
    internal static class GameplayTagConstants
    {
        public const string DefaultClassName = "Tags";

        public const string DefaultFileName = "GameplayTags.g.cs";

        /// <summary>
        /// The field that holds a parent's own tag, next to its children: Tags.Status.Tag.
        /// </summary>
        public const string SelfField = "Tag";

        /// <summary>
        /// The second line of the generated file, which tells it apart from a file written by hand.
        /// </summary>
        public const string HeaderMark = "// Made by UE Architecture from the gameplay tags";

        private const string TagType = "global::ModernWestern.UEArchitecture.GameplayTag";

        private static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
        {
            "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue", "decimal", "default", "delegate", "do",
            "double", "else", "enum", "event", "explicit", "extern", "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int",
            "interface", "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out", "override", "params", "private", "protected", "public",
            "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try",
            "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while"
        };

        /// <summary>
        /// The source of the constants file for these tags (valid ones only, with their parents), in
        /// <paramref name="namespaceName"/> (none when empty). <paramref name="collisions"/> gets one line per pair of
        /// sibling tags whose C# names clash ("X.Tag" and "X.Tag_" would both be Tag_).
        /// </summary>
        public static string Generate(IEnumerable<string> declared, string namespaceName, string className = DefaultClassName, ICollection<string> collisions = null)
        {
            var nodes = GameplayTagTree.Build(declared);

            className = string.IsNullOrWhiteSpace(className) ? DefaultClassName : Identifier(className.Trim(), Array.Empty<string>());

            var text = new StringBuilder();

            text.Append("// <auto-generated>\n");
            text.Append(HeaderMark).Append(" in Project Settings > UE Architecture.\n");
            text.Append("// Do not edit: press \"Generate C# constants\" again after changing the tags.\n");
            text.Append("// </auto-generated>\n\n");

            var hasNamespace = !string.IsNullOrWhiteSpace(namespaceName);

            var indent = hasNamespace ? 1 : 0;

            if (hasNamespace)
            {
                text.Append("namespace ").Append(namespaceName.Trim()).Append("\n{\n");
            }

            Line_Internal(text, indent, "/// <summary>");
            Line_Internal(text, indent, $"/// The project's gameplay tags: {className}.Status.Burning instead of GameplayTag.Request(\"Status.Burning\").");
            Line_Internal(text, indent, "/// </summary>");
            Line_Internal(text, indent, $"public static class {className}");
            Line_Internal(text, indent, "{");

            var topLevel = nodes.Where(node => node.Depth == 0).ToList();

            WriteMembers_Internal(text, nodes, topLevel, className, className, false, indent + 1, collisions);

            Line_Internal(text, indent, "}");

            if (hasNamespace)
            {
                text.Append("}\n");
            }

            return text.ToString();
        }

        /// <summary>
        /// A C# name for one part of a tag: "class" gives "@class", "1Up" gives "_1Up", and a name in
        /// <paramref name="taken"/> (the enclosing class, the Tag field, a sibling) gets '_' until it is free.
        /// </summary>
        public static string Identifier(string part, ICollection<string> taken)
        {
            var name = string.IsNullOrEmpty(part) ? "_" : part;

            if (char.IsDigit(name[0]))
            {
                name = "_" + name;
            }

            while (taken != null && taken.Contains(name))
            {
                name += "_";
            }

            return Keywords.Contains(name) ? "@" + name : name;
        }

        /// <summary>
        /// Null when a script in <paramref name="target"/> can use GameplayTag (it is, or references,
        /// UEArchitecture.Runtime); otherwise what to do.
        /// </summary>
        public static string AssemblyProblem(ScriptAssembly target, string path)
        {
            if (string.IsNullOrEmpty(target.Name) || target.Name.StartsWith("Assembly-CSharp", StringComparison.Ordinal))
            {
                // The predefined assemblies reference every auto-referenced asmdef, UE Architecture's runtime included.
                return null;
            }

            if (target.Name == ScriptWriter.RuntimeAssembly || target.References.Contains(ScriptWriter.RuntimeAssembly))
            {
                return null;
            }

            if (!target.Known)
            {
                return null;
            }

            var where = string.IsNullOrEmpty(target.AsmdefPath) ? target.Name : $"{target.Name} ({target.AsmdefPath})";

            return $"The assembly {where} does not reference {ScriptWriter.RuntimeAssembly}, so {System.IO.Path.GetFileName(path)} would not compile there. " +
                   $"Add {ScriptWriter.RuntimeAssembly} to its references, or pick another folder.";
        }

        /// <summary>
        /// True for a file this class wrote (it starts with the generator's header), which Generate may overwrite and the
        /// usage search leaves out.
        /// </summary>
        public static bool IsGenerated(string text)
        {
            if (string.IsNullOrEmpty(text))
            {
                return false;
            }

            text = text.TrimStart('﻿');

            return text.StartsWith("// <auto-generated>", StringComparison.Ordinal) && text.IndexOf(HeaderMark, 0, Math.Min(text.Length, 400), StringComparison.Ordinal) >= 0;
        }

        private static void WriteMembers_Internal(StringBuilder text, List<GameplayTagNode> nodes, List<GameplayTagNode> members, string enclosing, string enclosingPath, bool hasSelf,
                                                  int indent, ICollection<string> collisions)
        {
            var reserved = new List<string> { enclosing };

            if (hasSelf)
            {
                reserved.Add(SelfField);
            }

            // A class cannot be called like its own Tag field either.
            List<string> ReservedFor(GameplayTagNode node) => node.HasChildren ? reserved.Concat(new[] { SelfField }).ToList() : reserved;

            var names = new Dictionary<string, string>(StringComparer.Ordinal);

            var taken = new List<string>(reserved);

            // Names that need no escaping are claimed first, so a constant called like its tag always means that tag:
            // adding "X.Tag" never moves Tags.X.Tag_ away from "X.Tag_".
            foreach (var node in members.Where(node => Identifier(node.Leaf, ReservedFor(node)) == node.Leaf))
            {
                names[node.Name] = node.Leaf;

                taken.Add(node.Leaf);
            }

            foreach (var node in members.Where(node => !names.ContainsKey(node.Name)))
            {
                var alone = Identifier(node.Leaf, ReservedFor(node));

                var name = Identifier(node.Leaf, node.HasChildren ? taken.Concat(new[] { SelfField }).ToList() : taken);

                if (name != alone)
                {
                    var other = members.Where(sibling => names.TryGetValue(sibling.Name, out var siblingName) && siblingName.TrimStart('@') == alone.TrimStart('@'))
                                       .Select(sibling => sibling.Name)
                                       .FirstOrDefault();

                    collisions?.Add($"\"{node.Name}\" and \"{other ?? alone}\" would both be {enclosingPath}.{alone} in C#.");
                }

                names[node.Name] = name;

                taken.Add(name.TrimStart('@'));
            }

            // After a parent's own Tag field, its children start with a blank line too.
            var first = !hasSelf;

            foreach (var node in members)
            {
                var name = names[node.Name];

                if (!first)
                {
                    text.Append('\n');
                }

                first = false;

                if (!node.HasChildren)
                {
                    Field_Internal(text, indent, name, node.Name);

                    continue;
                }

                Line_Internal(text, indent, $"public static class {name}");
                Line_Internal(text, indent, "{");

                Field_Internal(text, indent + 1, SelfField, node.Name);

                var children = nodes.Where(child => child.Depth == node.Depth + 1 && child.Parent == node.Name).ToList();

                WriteMembers_Internal(text, nodes, children, name.TrimStart('@'), enclosingPath + "." + name, true, indent + 1, collisions);

                Line_Internal(text, indent, "}");
            }
        }

        private static void Field_Internal(StringBuilder text, int indent, string name, string tag)
        {
            Line_Internal(text, indent, $"public static readonly {TagType} {name} = {TagType}.Request(\"{tag}\");");
        }

        private static void Line_Internal(StringBuilder text, int indent, string line)
        {
            text.Append(' ', indent * 4).Append(line).Append('\n');
        }
    }
}
